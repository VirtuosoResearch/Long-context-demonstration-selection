def plot_term2(term2_results, save_dir):
    # ── Max residual ──
    fig_max, ax_max = plt.subplots(1, 1, figsize=(7, 6))
    # ── Weighted residual ──
    fig_wt, ax_wt = plt.subplots(1, 1, figsize=(7, 6))

    for g_item in term2_results["groups"]:
        gid = g_item["group"]
        n_arr = np.asarray(g_item["n_values"], dtype=float)
        max_arr = np.asarray(g_item["max_residual"], dtype=float)
        wt_arr = np.asarray(g_item["weighted_residual"], dtype=float)

        ax_max.loglog(n_arr, max_arr,
                      marker=GROUP_MARKERS[gid % len(GROUP_MARKERS)],
                      color=GROUP_COLORS[gid % len(GROUP_COLORS)],
                      label=rf'$\mathrm{{Group~{gid}}}$',
                      lw=3, markersize=8,
                      markevery=max(1, len(n_arr) // 15))
        ax_wt.loglog(n_arr, wt_arr,
                     marker=GROUP_MARKERS[gid % len(GROUP_MARKERS)],
                     color=GROUP_COLORS[gid % len(GROUP_COLORS)],
                     label=rf'$\mathrm{{Group~{gid}}}$',
                     lw=3, markersize=8,
                     markevery=max(1, len(n_arr) // 15))

    # Format max residual
    ax_max.tick_params(axis='both', labelsize=25)
    ax_max.set_xlabel(r'$\mathrm{HiPPO~state~dimension}~N$', fontsize=28)
    ax_max.set_ylabel(r'$\max_{i \leq K}\, \|(I-P_N)\,u_i^{(g)}\|^2$', fontsize=28)
    ax_max.legend(fontsize=20, loc='upper right')
    ax_max.grid(True, linestyle='--', linewidth=0.5, which='both')
    fig_max.tight_layout()
    path_max = os.path.join(save_dir, "term2_hippo_residual_max.pdf")
    fig_max.savefig(path_max)
    plt.close(fig_max)
    print(f"Saved: {path_max}")

    # Format weighted residual
    ax_wt.tick_params(axis='both', labelsize=25)
    ax_wt.set_xlabel(r'$\mathrm{HiPPO~state~dimension}~N$', fontsize=28)
    ax_wt.set_ylabel(r'$\sum_{i=1}^{K}\sigma_i^2\|(I-P_N)\,u_i^{(g)}\|^2$', fontsize=28)
    ax_wt.legend(fontsize=20, loc='upper right')
    ax_wt.grid(True, linestyle='--', linewidth=0.5, which='both')
    fig_wt.tight_layout()
    path_wt = os.path.join(save_dir, "term2_hippo_residual_weighted.pdf")
    fig_wt.savefig(path_wt)
    plt.close(fig_wt)
    print(f"Saved: {path_wt}")

    # Print slopes
    for g_item in term2_results["groups"]:
        gid = g_item["group"]
        sl_m = g_item["slope_max"]
        sm = g_item["smoothness_estimate"]
        sl_w = g_item["slope_weighted"]
        if sl_m is not None:
            print(f"Group {gid}: [max] slope={sl_m:.3f}, s≈{sm:.3f}")
        if sl_w is not None:
            print(f"Group {gid}: [weighted] slope={sl_w:.3f}")



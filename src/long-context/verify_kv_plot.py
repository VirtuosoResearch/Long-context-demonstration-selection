GROUP_COLORS = ['royalblue', 'darkorange', 'forestgreen', 'red',
                'mediumpurple', 'saddlebrown', 'deeppink', 'gray']
GROUP_MARKERS = ['o', 's', 'D', '^', 'v', 'P', 'X', 'h']


def piecewise_compress_x(x_vals, compress_until=50, left_ratio=1.0 / 3.0):
    x_vals = np.asarray(x_vals, dtype=float)
    x_min, x_max = float(np.min(x_vals)), float(np.max(x_vals))
    if x_max <= x_min or compress_until <= x_min or compress_until >= x_max:
        return x_vals.copy()
    ratio = float(np.clip(left_ratio, 0.05, 0.95))
    out = np.empty_like(x_vals, dtype=float)
    left = x_vals <= compress_until
    out[left] = ((x_vals[left] - x_min) / (compress_until - x_min)) * ratio
    out[~left] = ratio + ((x_vals[~left] - compress_until) / (x_max - compress_until)) * (1.0 - ratio)
    out = x_min + out * (x_max - x_min)
    return out


def choose_xticks_with_labels(x_min, x_max):
    cands = [1, 2, 5, 10, 20, 30, 40, 50, 75, 100, 150, 200, 300, 500, 800, 1000, 1500, 2000]
    raw = [x for x in cands if x_min <= x <= x_max]
    if not raw:
        raw = np.linspace(x_min, x_max, 6).astype(int).tolist()
    if x_min not in raw:
        raw.insert(0, int(x_min))
    if x_max not in raw:
        raw.append(int(x_max))
    raw = sorted(set(raw))
    return np.array(raw, dtype=float), [rf'$\mathrm{{{int(x)}}}$' for x in raw]


def prune_tick_labels(raw_ticks, scaled_ticks, min_gap_ratio=0.07):
    raw_ticks = np.asarray(raw_ticks, dtype=float)
    scaled_ticks = np.asarray(scaled_ticks, dtype=float)
    if len(raw_ticks) <= 2:
        return raw_ticks
    span = float(np.max(scaled_ticks) - np.min(scaled_ticks))
    if span <= 0:
        return raw_ticks
    min_gap = min_gap_ratio * span
    keep_idx = [0]
    last_idx = 0
    for i in range(1, len(raw_ticks) - 1):
        if (scaled_ticks[i] - scaled_ticks[last_idx]) >= min_gap:
            keep_idx.append(i)
            last_idx = i
    keep_idx.append(len(raw_ticks) - 1)
    keep_idx = sorted(set(keep_idx))
    return raw_ticks[keep_idx]


def latex_sci_formatter(val, pos):
    """Format y-axis tick in LaTeX scientific notation."""
    if val == 0:
        return r'$\mathrm{0}$'
    exp = int(np.floor(np.log10(abs(val))))
    coeff = val / 10 ** exp
    if abs(coeff - 1.0) < 0.01:
        return rf'$10^{{{exp}}}$'
    return rf'${coeff:.1f} \times 10^{{{exp}}}$'



def main():
    p = argparse.ArgumentParser()
    p.add_argument("--results_path", type=str, required=True)
    p.add_argument("--save_dir", type=str, default="")
    p.add_argument("--x_compress_until", type=int, default=50)
    p.add_argument("--x_left_ratio", type=float, default=1.0 / 3.0)
    args = p.parse_args()

    data = torch.load(args.results_path, map_location="cpu")
    if args.save_dir:
        save_dir = args.save_dir
    else:
        save_dir = os.path.dirname(args.results_path) or "."
    os.makedirs(save_dir, exist_ok=True)

    print(f"Loaded results from: {args.results_path}")
    plot_term1(
        data["term1"],
        save_dir,
        x_compress_until=args.x_compress_until,
        x_left_ratio=args.x_left_ratio,
    )
    plot_term2(data["term2"], save_dir)
    print(f"All figures saved to: {save_dir}")


if __name__ == "__main__":
    main()
def plot_term1(term1_results, save_dir, x_compress_until=50, x_left_ratio=1.0 / 3.0):
    for item in term1_results:
        prefix_len = item["prefix_length"]
        groups = item["groups"]
        suffix = f"L{prefix_len}"

        # ── Singular value decay ──
        fig, ax = plt.subplots(1, 1, figsize=(7, 6))
        x_max = 1
        for g_item in groups:
            gid = g_item["group"]
            s_sq = np.asarray(g_item["singular_values_sq"], dtype=float)
            x_raw = np.arange(1, len(s_sq) + 1, dtype=float)
            x_sc = piecewise_compress_x(x_raw, x_compress_until, x_left_ratio)
            ax.semilogy(x_sc, s_sq,
                        marker=GROUP_MARKERS[gid % len(GROUP_MARKERS)],
                        color=GROUP_COLORS[gid % len(GROUP_COLORS)],
                        label=rf'$\mathrm{{Group~{gid}}}$',
                        lw=3, markersize=8,
                        markevery=max(1, len(s_sq) // 15))
            x_max = max(x_max, len(s_sq))

        tr, _ = choose_xticks_with_labels(1, x_max)
        tr_sc = piecewise_compress_x(tr, x_compress_until, x_left_ratio)
        tr_keep = prune_tick_labels(tr, tr_sc, min_gap_ratio=0.08)
        tr_keep_sc = piecewise_compress_x(tr_keep, x_compress_until, x_left_ratio)
        ax.set_xticks(tr_keep_sc)
        ax.set_xticklabels([rf'$\mathrm{{{int(x)}}}$' for x in tr_keep], fontsize=25)
        ax.tick_params(axis='y', labelsize=25)
        ax.set_xlabel(r'$\mathrm{Singular~value~index}~j$', fontsize=28)
        ax.set_ylabel(r'$\sigma_j^2(K^{(g)})$', fontsize=28)
        ax.legend(fontsize=20, loc='upper right')
        ax.grid(True, linestyle='--', linewidth=0.5)
        fig.tight_layout()
        fig.savefig(os.path.join(save_dir, f"term1_sv_decay_{suffix}.pdf"))
        plt.close(fig)

        # ── Tail energy ──
        fig2, ax2 = plt.subplots(1, 1, figsize=(7, 6))
        n_max = 1
        for g_item in groups:
            gid = g_item["group"]
            e_n = np.asarray(g_item["tail_energy"], dtype=float)
            n_vals = np.arange(1, len(e_n) + 1, dtype=float)
            n_max = max(n_max, len(e_n))
            n_sc = piecewise_compress_x(n_vals, x_compress_until, x_left_ratio)
            ax2.semilogy(n_sc, e_n,
                         marker=GROUP_MARKERS[gid % len(GROUP_MARKERS)],
                         color=GROUP_COLORS[gid % len(GROUP_COLORS)],
                         label=rf'$\mathrm{{Group~{gid}}}$',
                         lw=3, markersize=8,
                         markevery=max(1, len(e_n) // 15))

        tr2, _ = choose_xticks_with_labels(1, n_max)
        tr2_sc = piecewise_compress_x(tr2, x_compress_until, x_left_ratio)
        tr2_keep = prune_tick_labels(tr2, tr2_sc, min_gap_ratio=0.08)
        tr2_keep_sc = piecewise_compress_x(tr2_keep, x_compress_until, x_left_ratio)
        ax2.set_xticks(tr2_keep_sc)
        ax2.set_xticklabels([rf'$\mathrm{{{int(x)}}}$' for x in tr2_keep], fontsize=25)
        ax2.tick_params(axis='y', labelsize=25)
        ax2.set_xlabel(r'$\mathrm{HiPPO~state~dimension}~N$', fontsize=28)
        ax2.set_ylabel(r'$E_N^{(g)} = \sum_{j>N} \sigma_j^2$', fontsize=28)
        ax2.legend(fontsize=20, loc='upper right')
        ax2.grid(True, linestyle='--', linewidth=0.5)
        fig2.tight_layout()
        fig2.savefig(os.path.join(save_dir, f"term1_tail_energy_{suffix}.pdf"))
        plt.close(fig2)
        print(f"Saved Check 1 figures for L={prefix_len}.")


